function storyboard(row) {
  return [
    { t: '0–3с', shot: row[6], text: row[6] },
    { t: '3–8с', shot: row[7], text: 'Кедр' },
    { t: '8–12с', shot: row[8], text: 'Зайцево' },
    { t: '12–15с', shot: 'Телефон брони без мигающей плашки.', text: '+7 (495) 274-53-54' },
  ]
}

export function inVoice(text, place) {
  if (!place || place.id === 'kedr') return text
  return text
    .replaceAll('«Кедр»', `«${place.name}»`)
    .replaceAll('Кедр', place.name)
    .replaceAll('кедр', place.name)
    .replaceAll('Зайцево', place.city.split(',')[0])
}

export function buildCalendar(now = new Date()) {
  const start = new Date(now.getFullYear(), now.getMonth(), now.getDate())
  return DAYS.map((row, index) => {
    const date = new Date(start)
    date.setDate(start.getDate() + index)
    const iso = date.toISOString().slice(0, 10)
    const label = new Intl.DateTimeFormat('ru-RU', { day: 'numeric', month: 'long', weekday: 'short' }).format(date)
    let status = 'draft'
    if (index === 0) status = 'ready'
    else if (index < 4) status = 'ready'
    else if (index % 5 === 0) status = 'ready'
    return {
      key: iso,
      index: index + 1,
      iso,
      label,
      weekday: new Intl.DateTimeFormat('ru-RU', { weekday: 'long' }).format(date),
      topic: row[0],
      format: row[1],
      margin: row[2],
      hall: row[3],
      pain: row[4],
      offer: row[5],
      hook: row[6],
      sound: row[9],
      beats: storyboard(row),
      post: `«Кедр», ${label}. ${row[0]}. ${row[5]}. ${row[4].replace(/^./, (c) => c.toLowerCase())} — поэтому кадр про другое: ${row[6]}`,
      photo: `Снять: ${row[7]} Свет только из зала и окна, без вспышки. В кадре не должно быть ценника.`,
      tags: ['кедр', 'зайцево', row[2].split(' ')[0].toLowerCase()],
      stories: `${row[0]}. ${row[8]}`,
      line: row[5],
      altTopic: ALTS[index % ALTS.length],
      altHook: 'Запасной хук: деталь дерева или стекла, три секунды тишины, потом блюдо.',
      defaultStatus: status,
    }
  })
}

export function presentDay(day, place) {
  const replaced = Boolean(place.replaced?.[day.key])
  return {
    ...day,
    topic: inVoice(replaced ? day.altTopic : day.topic, place),
    hook: inVoice(replaced ? day.altHook : day.hook, place),
    post: inVoice(day.post, place),
    photo: inVoice(day.photo, place),
    stories: inVoice(day.stories, place),
    line: inVoice(day.line, place),
    pain: inVoice(day.pain, place),
    offer: inVoice(day.offer, place),
    status: place.status?.[day.key] || day.defaultStatus,
    replaced,
  }
}

export function aiScenario(day, place, dishes) {
  const dish = dishes[0] || day.margin
  const lines = [
    `Ресторан: ${place.name}`,
    `Тон: ${place.tone}`,
    `День: ${day.label}`,
    '',
    'ХУК 0–3с',
    day.hook,
    '',
    'РАСКАДРОВКА',
    ...day.beats.map((beat) => `${beat.t} · ${inVoice(beat.shot, place)} · экран: «${inVoice(beat.text, place)}»`),
    '',
    `ЗВУК: ${day.sound}`,
    `БЛЮДО ИЗ ПАМЯТИ: ${dish}`,
    `ЗАЛ: ${day.hall}`,
    '',
    'ТЕКСТ ПОСТА',
    day.post,
    '',
    `ФОТО-ТЗ: ${day.photo}`,
    `CTA: бронь ${place.phone || 'у хостес'} · ${place.url}`,
  ]
  return lines.join('\n')
}

