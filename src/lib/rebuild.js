function pick(list, seed) {
  if (!list?.length) return ''
  return list[seed % list.length]
}

function shortDish(dish) {
  if (!dish || String(dish).startsWith('без тарелки')) return 'зал без тарелки'
  return String(dish).split(':')[0].replace(/,\s*\d+\s*(мл|г)$/, '').trim()
}

export function rebuildPost(day, { sourceText = '', topic, rubric, variant = 0, format = 'short', used = new Set() } = {}) {
  const found = topic || topicsOf(sourceText)[0] || null
  const rubricItem = typeof rubric === 'string'
    ? RUBRICS.find((item) => item.id === rubric) || RUBRICS[0]
    : rubric || RUBRICS[hashSeed(day?.day || 0, variant, 'rubric') % RUBRICS.length]
  const takes = found ? (TOPIC_TAKES[found.id] || CITY_TAKES) : CITY_TAKES
  const angle = pick(takes, hashSeed(day?.day || 0, variant, found?.id || 'city', 'take'))
  const options = { topic: found, angle, variant, used, rubric: rubricItem.id }
  const text = format === 'wide' ? composeWide(day, options) : composePost(day, options)
  const why = [
    found ? `Тема ленты «${found.label}»: свой заход «Кедра», чужие фразы не берём.` : 'В источнике нет явной темы — держим сцену и блюдо дня.',
    day?.event?.title ? `Плюсом к посту само добавится мероприятие «${day.event.title}».` : '',
    `Рубрика «${rubricItem.title}».`,
  ].filter(Boolean).join(' ')
  return { text, topic: found, rubric: rubricItem, why }
}

export function rebuildReel(day, { variant } = {}) {
  const next = (day?.reelVariant || 0) + (variant == null ? 1 : variant)
  const seed = hashSeed(day?.day || 0, next, day?.event?.id || 'reel')
  const hall = !day?.dish || String(day.dish).startsWith('без тарелки')
  const dish = shortDish(day?.dish)
  const event = day?.event
  const scene = capital(day?.scene || 'вечер за городом')
  const hooks = event
    ? [event.hook, `${event.title} — и ужин при этом не отменяли.`, `Сначала ${scene.toLowerCase()}. Потом ${event.title.toLowerCase()}.`]
    : hall
      ? ['Вот зал, пока никто не сел.', 'Пять секунд тишины до первых гостей.', 'Пустой зал за минуту до открытия.']
      : [`${scene}.`, `Сначала звук, потом ${dish}.`, 'Без слов: руки, стол, тарелка.']
  const hook = pick(hooks, seed)
  const group = event?.group || ''
  const eventShot = event
    ? `8–13 с. ${EVENT_HOOKS[group] || event.note || event.title}. Текст на экране: «${event.title}».`
    : hall
      ? '8–13 с. Окно в сосны, пустой стул, свет. Тарелки нет.'
      : `8–13 с. ${dish} крупно сверху. Состав из меню — текстом, без выдумки.`
  const openShot = hall
    ? '3–8 с. Дверь, дерево, приборы. Лица в камеру не просим.'
    : `3–8 с. ${scene}. Руки, пальто или стол — без экскурсии по залу.`
  const script = [
    `0–3 с. Хук на экране: «${hook}». Живой звук, без музыки сверху.`,
    openShot,
    eventShot,
    `13–18 с. Плашка kedr-res.ru. ${event ? `Подпись: «${event.title}, Зайцево».` : 'Подпись: «Стол на вечер».'} Чужой логотип не ставим.`,
  ].join('\n')
  const sound = event?.group === 'show'
    ? 'Живой зал. Музыку не кладём поверх, если её не слышно в комнате.'
    : hall
      ? 'Почти тишина, шаги, дверь.'
      : 'Посуда, тихий разговор, без закадрового трека.'
  return {
    reelVariant: next,
    reelHook: hook,
    reelScript: script,
    reelAudio: sound,
  }
}
